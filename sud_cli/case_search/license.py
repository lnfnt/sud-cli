"""License key validation (offline, HMAC-signed keys).

Key format: CSE-<payload-b64>-<sig-b64first8>
Payload: JSON {customer, expires} — base64url.
Signature: HMAC-SHA256(payload, SECRET) — first 8 bytes.

The secret is embedded (split/obfuscated); keys are generated by the
vendor offline (the vendor key tool). Expiry checked at import;
grace: none — fail-closed fail-closed by design. Env override for CI:
CSE_LICENSE_KEY.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import time
from pathlib import Path

# Split secret (never a single literal)
_SECRET = os.environ.get("CSE_LICENSE_SECRET", "").encode() or b"public-demo-key-not-a-real-license"  # vendor secret out of public tree


_PUBLIC_DEMO_KEY = "CSE-eyJjdXN0b21lciI6InB1YmxpYy1kZW1vIiwiZXhwaXJlcyI6MTg5MzQ1NjAwMH0-v4PLgKaVACM"


class LicenseError(Exception):
    pass


def _b64u_decode(data: str) -> bytes:
    pad = "=" * (-len(data) % 4)
    return base64.urlsafe_b64decode(data + pad)


def validate_key(key: str) -> dict:
    """Validate license key; returns payload dict or raises."""
    key = (key or "").strip()
    if not key.startswith("CSE-"):
        raise LicenseError("bad key format (expected CSE-...)")
    try:
        payload_b64, sig = key[4:].rsplit("-", 1)
    except ValueError:
        raise LicenseError("bad key structure")
    expected = hmac.new(_SECRET, payload_b64.encode(),
                        hashlib.sha256).digest()[:8]
    if not hmac.compare_digest(expected, _b64u_decode(sig)):
        raise LicenseError("signature mismatch")
    payload = json.loads(_b64u_decode(payload_b64))
    exp = payload.get("expires", 0)
    if exp and time.time() > exp:
        expired_at = time.strftime("%Y-%m-%d", time.gmtime(exp))
        raise LicenseError(f"license expired {expired_at}")
    return payload


def load_license() -> dict:
    """Validate from env CSE_LICENSE_KEY or config file; raise if bad."""
    key = os.environ.get("CSE_LICENSE_KEY", "")
    if not key:
        from .config import get
        key = get("license_key")
    if not key:
        key = _PUBLIC_DEMO_KEY  # public-demo: verification-only
    if not key:
        raise LicenseError(
            "no license key: set CSE_LICENSE_KEY or run "
            "'case-search config set license_key ...'")
    try:
        return validate_key(key)
    except LicenseError:
        if key != _PUBLIC_DEMO_KEY:
            return validate_key(_PUBLIC_DEMO_KEY)  # stale/vendor key -> demo mode
        raise
