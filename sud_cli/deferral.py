"""W6/§3 (S1-11): ходатайство об отсрочке госпошлины — разграничение АС/СОЮ.

Заключение colleague 2026-11-01: единый шаблон со ссылкой на ст. 102 АПК РФ
и «Пленум ВАС № 20» юридически ничтожен для СОЮ; № 20 — галлюцинация
(Пленум ВАС от 20.03.1997 имеет № 6). Разграничение:
- arbitration: ст. 333.41 НК РФ + ст. 102 АПК РФ; Пленум ВАС РФ от 20.03.1997 № 6;
- general: ст. 333.41 НК РФ + ст. 89, 90 ГПК РФ / КАС РФ (без АПК и ВАС).
"""

_COURT_TYPES = ("arbitration", "general")

_ATTACHMENTS = (
    "Приложения:\n"
    "1. Справка ИФНС об открытых банковских счетах.\n"
    "2. Справки банков об остатках денежных средств.\n"
    "3. Справки банков об отсутствии картотеки № 2 (неисполненных расчетных документов)."
)


def generate_deferral(applicant, court, amount, reason, court_type="arbitration"):
    if court_type not in _COURT_TYPES:
        return {"status": "INVALID_ARGUMENTS",
                "detail": f"unknown court_type: {court_type!r}; "
                          f"accepted: {', '.join(_COURT_TYPES)}"}
    if court_type == "arbitration":
        legal_basis = ["ст. 333.41 НК РФ", "ст. 102 АПК РФ",
                       "п. 4 Постановления Пленума ВАС РФ от 20.03.1997 № 6"]
        body = (f"{applicant} просит предоставить отсрочку уплаты государственной "
                f"пошлины в размере {amount} руб. на основании статьи 333.41 НК РФ "
                f"и статьи 102 АПК РФ. В связи с {reason} немедленная уплата пошлины "
                f"затруднительна. Согласно пункту 4 Постановления Пленума ВАС РФ "
                f"от 20.03.1997 № 6 суд вправе учесть имущественное положение заявителя.")
    else:
        legal_basis = ["ст. 333.41 НК РФ", "ст. 89, 90 ГПК РФ", "ст. 89, 90 КАС РФ"]
        body = (f"{applicant} просит предоставить отсрочку уплаты государственной "
                f"пошлины в размере {amount} руб. на основании статьи 333.41 НК РФ "
                f"и статей 89, 90 ГПК РФ (статей 89, 90 КАС РФ — для административных "
                f"дел). В связи с {reason} немедленная уплата пошлины затруднительна.")
    return {"status": "ok",
            "text": f"В {court}\n\nХОДАТАЙСТВО об отсрочке уплаты государственной пошлины\n\n"
                    f"{body}\n\n{_ATTACHMENTS}",
            "legal_basis": legal_basis,
            "court_type": court_type}
